/*
 6. Retrieve the total sales amount (salesorderheader table) for each product
 category and sales reason for sales made on or after May 30th, 2011. Only include
 sales that are associated with products that had a special offer applied.
 Include only product categories with total sales greater than $100,000.
 Order the result set by total sales amount in descending order.
 */

USE adventureworks;
SELECT
    pc.Name AS product_category,
    sr.Name AS sales_reason,
    SUM(soh.TotalDue) AS total_sales
FROM sales_salesorderheader soh
JOIN sales_salesorderdetail sod ON soh.SalesOrderID = sod.SalesOrderID
JOIN production_product p ON sod.ProductID = p.ProductID
JOIN production_productsubcategory psc ON p.ProductSubcategoryID = psc.ProductSubcategoryID
JOIN production_productcategory pc ON psc.ProductCategoryID = pc.ProductCategoryID
JOIN sales_specialofferproduct sop ON p.ProductID = sop.ProductID
JOIN sales_salesorderheadersalesreason sohsr ON soh.SalesOrderID = sohsr.SalesOrderID
JOIN sales_salesreason sr ON sohsr.SalesReasonID = sr.SalesReasonID
WHERE soh.OrderDate >= '2011-05-30'
GROUP BY pc.Name, sr.Name
HAVING SUM(soh.TotalDue) > 100000
ORDER BY total_sales DESC;

/*
 7. Retrieve the product ID, total sales amount, number of sales lines, product name,
 a shortened version of the product name (first 10 characters), and the price
 category for all products sold in 2013 with total sales exceeding $50,000. Classify products
 into price categories based on their list price: 'High-End' for prices $1000 or more,
 'Mid-Range' for prices between $500 and $999, and 'Budget' for prices below $500.
 Order the results by total sales amount in descending order. Solve the task using a derived table.
 */

SELECT
    dt.ProductID,
    dt.total_sales,
    dt.sales_lines,
    dt.Name,
    LEFT(dt.Name, 10) AS short_name,
    CASE
        WHEN dt.ListPrice >= 1000 THEN 'High-End'
        WHEN dt.ListPrice >= 500 THEN 'Mid-Range'
        ELSE 'Budget'
    END AS price_category
FROM (
    SELECT
        p.ProductID,
        p.Name,
        p.ListPrice,
        SUM(sod.LineTotal) AS total_sales,
        COUNT(*) AS sales_lines
    FROM sales_salesorderdetail sod
    JOIN sales_salesorderheader soh ON sod.SalesOrderID = soh.SalesOrderID
    JOIN production_product p ON sod.ProductID = p.ProductID
    WHERE YEAR(soh.OrderDate) = 2013
    GROUP BY p.ProductID, p.Name, p.ListPrice
) dt
WHERE dt.total_sales > 50000
ORDER BY total_sales DESC;


/*
 8. Retrieve the product ID, product name (or 'No Name' if the name is missing),
 the first 10 characters of the product name, the year the product was first sold,
 and the release category for all products with total sales exceeding $50,000 in 2013.
 Classify products into release categories based on the year they were first sold:
 'Legacy' for products introduced in 2011 or earlier, 'Mid-Lifecycle'
 for those introduced in 2012, and 'New Release' for those introduced in 2013 or later.
 Order the result set alphabetically by product name.
 */
SELECT
    p.ProductID,
    IFNULL(p.Name, 'No Name') AS product_name,
    LEFT(IFNULL(p.Name, 'No Name'), 10) AS short_name,
    YEAR(MIN(soh.OrderDate)) AS first_sold_year,
    CASE
        WHEN YEAR(MIN(soh.OrderDate)) <= 2011 THEN 'Legacy'
        WHEN YEAR(MIN(soh.OrderDate)) = 2012 THEN 'Mid-Lifecycle'
        ELSE 'New Release'
    END AS release_category
FROM sales_salesorderdetail sod
JOIN sales_salesorderheader soh ON sod.SalesOrderID = soh.SalesOrderID
JOIN production_product p ON sod.ProductID = p.ProductID
WHERE YEAR(soh.OrderDate) = 2013
GROUP BY p.ProductID, p.Name
HAVING SUM(sod.LineTotal) > 50000
ORDER BY product_name;

/*
 9. Retrieve the sales order ID, order number (formatted as 'SO-[SalesOrderID]'),
 the number of days since the start of the calendar (using the TO_DAYS function),
 the order year, freight cost (with NULL values replaced by 0), total due amount,
 and a running total of the total due. The running total is calculated in order of
 the sales order date, including all prior rows up to the current one. Order the
 result set by the sales order date.
 */
SELECT
    SalesOrderID,
    CONCAT('SO-', SalesOrderID) AS order_number,
    TO_DAYS(OrderDate) AS days_since_calendar_start,
    YEAR(OrderDate) AS order_year,
    IFNULL(Freight, 0) AS freight,
    TotalDue,
    SUM(TotalDue) OVER (
        ORDER BY OrderDate
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS running_total
FROM sales_salesorderheader
ORDER BY OrderDate;

/*
 10. Retrieve all departments (present ID and name) with the average and maximum
 sick leave hours of their employees. Only include departments with more than
 10 employees and whose job titles have more than 5 characters.
 Order the results by the average sick leave hours in descending order.
 */

SELECT
    d.DepartmentID,
    d.Name,
    AVG(e.SickLeaveHours) AS avg_sick_leave,
    MAX(e.SickLeaveHours) AS max_sick_leave
FROM humanresources_department d
JOIN humanresources_employeedepartmenthistory edh ON d.DepartmentID = edh.DepartmentID
JOIN humanresources_employee e ON edh.BusinessEntityID = e.BusinessEntityID
WHERE LENGTH(e.JobTitle) > 5
GROUP BY d.DepartmentID, d.Name
HAVING COUNT(*) > 10
ORDER BY avg_sick_leave DESC;

