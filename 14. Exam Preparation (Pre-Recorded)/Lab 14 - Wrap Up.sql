/*
 1. Retrieve the rental ID, rental date, days since the rental, return status,
 and customer name for all rentals. Calculate the days since the rental date
 using the current date. Determine the return status as 'Overdue' if the
 rental period (difference between return date and rental date)
 exceeds 3 days; otherwise, mark it as 'OnTime.' Format the customer name by
 concatenating the first and last names, converting it to uppercase, padding
 it to 30 characters with asterisks, and replacing null values with 'UNKNOWN.'
 Order the result set by days since the rental in descending order.
 */

 USE sakila;

SELECT
    r.rental_id,
    r.rental_date,
    DATEDIFF(curdate(), r.rental_date) AS days_since_the_rental,
    IF(DATEDIFF(r.return_date, r.rental_date) > 3, 'Overdue', 'OnTime') AS return_status,
    CONCAT(
            IFNULL(UPPER(c.first_name), 'UNKNOWN'),
            ' ',
            IFNULL(UPPER(c.last_name), 'UNKNOWN'),
            REPEAT(
                    '*',
                    30 - CHAR_LENGTH(CONCAT(
                            IFNULL(UPPER(c.first_name), 'UNKNOWN'),
                            ' ',
                            IFNULL(UPPER(c.last_name), 'UNKNOWN')
                            )
                    )
            )
    ) AS customer_name
FROM rental r
JOIN customer c ON r.customer_id = c.customer_id
ORDER BY days_since_the_rental DESC;

/*
 2. Retrieve the film ID, a fancy title (film title generated by reversing
 the first five characters of the title in uppercase and appending the rest
 of the title in lowercase), description length, average payment amount
 rounded to 2 decimal points, total unique customers who rented the film,
 bit status of the film ID ('BITTY' if the binary representation of the film
 ID has more than 4 set bits, otherwise 'NOT BITTY.'), and cost category for
 films rented by more than 5 customers. Classify the cost category of the
 film as 'ABOVE AVG COST' if its replacement cost is greater than the average
 replacement cost of all films, otherwise 'BELOW AVG COST.' Order the result
 set by average payment in descending order, by the fancy title alphabetically.
 */

SELECT
    f.film_id,
    CONCAT(
            REVERSE(UPPER(SUBSTRING(f.title, 1, 5))),
            LOWER(SUBSTRING(f.title, 6, LENGTH(f.title) - 5))
    ) AS fancy_title,
    LENGTH(f.description) AS description_length,
    ROUND(AVG(p.amount), 2) AS average_payment_amount,
    COUNT(DISTINCT r.customer_id) AS no_unique_customers,
    IF(BIT_COUNT(f.film_id) > 4, 'BITTY', 'NOT BITTY') AS bit_status,
    IF(
            f.replacement_cost > (
                SELECT AVG(replacement_cost) FROM film
            ),
            'ABOVE AVG COST',
            'BELOW AVG COOST'
    ) AS cost_category
FROM film f
JOIN inventory i ON f.film_id = i.film_id
JOIN rental r ON i.inventory_id = r.inventory_id
JOIN payment p ON r.rental_id = p.rental_id
JOIN film_category fc ON f.film_id = fc.film_id
JOIN category c ON fc.category_id = c.category_id
GROUP BY f.film_id
HAVING COUNT(r.customer_id) > 5
ORDER BY average_payment_amount DESC, fancy_title ASC;

/*
 3. Retrieve the film ID, total revenue, rental count, film title,
 a shortened version of the title (first 10 characters), and the price
 category for all films with total revenue exceeding $100 from payments
 made between 2004 and 2006. Classify films into price categories based
 on their rental rate: 'Premium' for rates $3.00 or higher, 'Standard'
 for rates between $2.00 and $2.99, and 'Budget' for rates below $2.00.
 Order the result set by the film title in ascending order.
 Solve the task using a derived table.
 */

 SELECT
    dt.film_id,
    dt.total_revenue,
    dt.rental_count,
    dt.title,
    LEFT(dt.title, 10) AS short_title,
    CASE
        WHEN dt.rental_rate >= 3 THEN 'Premium'
        WHEN dt.rental_rate >= 2 THEN 'Standard'
        ELSE 'Budget'
    END AS price_category
FROM (
    SELECT
        f.film_id,
        f.title,
        f.rental_rate,
        SUM(p.amount) AS total_revenue,
        COUNT(r.rental_id) AS rental_count
    FROM film f
    JOIN inventory i ON f.film_id = i.film_id
    JOIN rental r ON i.inventory_id = r.inventory_id
    JOIN payment p ON r.rental_id = p.rental_id
    WHERE YEAR(p.payment_date) BETWEEN 2004 AND 2006
    GROUP BY f.film_id, f.title, f.rental_rate
) dt
WHERE dt.total_revenue > 100
ORDER BY dt.title;

/*
 4. Retrieve the order number, order date, days since the order was placed,
 shipping status, and customer name for all orders. Calculate the number
 of days since the order date, and mark the shipping status as 'Overdue'
 if the shipping duration exceeds 3 days; otherwise, mark it as 'OnTime.'
 Customer names need to be in uppercase, padded them to 30 characters
 with asterisks, and replacing null values with 'UNKNOWN.' Order the result
 set by days since the order was placed in descending order.
 */
USE classicmodels;
SELECT
    o.orderNumber,
    o.orderDate,
    DATEDIFF(CURDATE(), o.orderDate) AS days_since_order,
    IF (DATEDIFF(o.shippedDate, o.orderDate) > 3, 'Overdue', 'OnTime') AS shipping_status,
    CONCAT(
        REPEAT('*',
            30 - CHAR_LENGTH(IFNULL(UPPER(c.customerName), 'UNKNOWN'))
        ),
        IFNULL(UPPER(c.customerName), 'UNKNOWN')
    ) AS customer_name
FROM orders o
LEFT JOIN customers c ON o.customerNumber = c.customerNumber
ORDER BY days_since_order DESC;

/*
 5. Retrieve the customer ID, the customer name in lowercase, the first 5 characters
 of the customer name reversed, the total number of orders, and count of overdue orders
 for all customers with more than two overdue orders. Overdue orders are defined as
 those placed over 30 days ago. Additionally, format the customer's phone number by
 extracting the country code if it starts with a '+', or label it as "Bad format" otherwise.
 Determine the customer's bit status as 'HIGH-BIT' if the bit count of their ID exceeds 5, or
 'LOW-BIT' otherwise. Order the result set by the number of overdue orders in descending order.
 */
SELECT
    c.customerNumber,
    LOWER(c.customerName) AS customer_name,
    REVERSE(LEFT(c.customerName, 5)) AS reversed_name,
    COUNT(o.orderNumber) AS total_orders,
    SUM(
        CASE
            WHEN DATEDIFF(CURDATE(), o.orderDate) > 30 THEN 1
            ELSE 0
        END
    ) AS overdue_orders,
    CASE
        WHEN c.phone LIKE '+%' THEN SUBSTRING_INDEX(c.phone, ' ', 1)
        ELSE 'Bad format'
    END AS phone_format,
    CASE
        WHEN BIT_COUNT(c.customerNumber) > 5 THEN 'HIGH-BIT'
        ELSE 'LOW-BIT'
    END AS bit_status
FROM customers c
JOIN orders o ON c.customerNumber = o.customerNumber
GROUP BY c.customerNumber, c.customerName, c.phone
HAVING overdue_orders > 2
ORDER BY overdue_orders DESC;

